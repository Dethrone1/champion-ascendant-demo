#!/usr/bin/env python3
"""Export the scoring tables from the Python formulas to static/ascent_tables.js.

The Python files are the source of truth. The browser calculator and the
Both Systems board read the generated file, so the website can never carry a
second, hand-copied version of a lookup table.

Run after changing any table in scoring/:
    python scoring/export_tables.py
CI fails if the committed file is out of date (scoring/test_parity.py).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import one_ascent_v3_9 as one   # noqa: E402
import dwcs_ascent_v3_0 as dwcs  # noqa: E402

OUT = os.path.join(HERE, "..", "static", "ascent_tables.js")

# Promotion codes. The private formula keys them in PROMOTIONS (with signing
# counts); the public copy keys them in PROMO_TABLE (points only).
PROMO_CODES = list(getattr(one, "PROMOTIONS", None) or one.PROMO_TABLE)


def build() -> str:
    one_tables = {
        "version": "3.9",
        "FR_WEIGHT": one.FR_WEIGHT,
        "WR_WEIGHT": one.WR_WEIGHT,
        "GLOBAL_FR_AVG": one.GLOBAL_FR_AVG,
        "FR_NORM_CEILING": one.FR_NORM_CEILING,
        "SHRINK_K": one.SHRINK_K,
        "UNDEFEATED_BONUS": one.UNDEFEATED_BONUS,
        "UNDEFEATED_MIN_WINS": one.UNDEFEATED_MIN_WINS,
        "UNLISTED_PROMO": one.UNLISTED_PROMO,
        "UNKNOWN_ORIGIN": one.UNKNOWN_ORIGIN,
        "AGE_BANDS": one.AGE_BANDS,
        "AGE_OLDER": one.AGE_OLDER,
        "TITLE_BASE": one.TITLE_BASE,
        "TITLE_PER_WIN": one.TITLE_PER_WIN,
        "WC_AVG": one.WC_AVG,
        "ORIGIN_FIT": one.ORIGIN_FIT,
        # Points per promotion code, worked out by the Python. The raw signing
        # counts behind them stay out of the public page.
        "PROMO_POINTS": {k: one.promo_points(k) for k in PROMO_CODES},
        "PROMO_HQ_BONUS": {k: one.hq_bonus(k) for k in PROMO_CODES},
        "COUNTRY_REGION": {k: v for k, v in one.COUNTRY_REGION.items() if v},
    }
    dwcs_tables = {
        "version": "3.0",
        "FR_WEIGHT": dwcs.FR_WEIGHT,
        "WIN_WEIGHT": dwcs.WIN_WEIGHT,
        "STREAK_MULT": dwcs.STREAK_MULT,
        "ELITE_FINISHER_BONUS": dwcs.ELITE_FINISHER_BONUS,
        "HOT_STREAK_BONUS": dwcs.HOT_STREAK_BONUS,
        "HOT_STREAK_THRESHOLD": dwcs.HOT_STREAK_THRESHOLD,
        "LOSS_BAND": {str(k): v for k, v in dwcs.LOSS_BAND.items()},
        "LOSS_BAND_DEFAULT": dwcs.LOSS_BAND_DEFAULT,
        "WC_FR_AVG": dwcs.WC_FR_AVG,
        "OVERALL_FR_AVG": dwcs.OVERALL_FR_AVG,
        "FR_RATIO_CAP": dwcs.FR_RATIO_CAP,
        "ANCHOR_SLOPE": dwcs.ANCHOR_SLOPE,
        "ANCHOR_INTERCEPT": dwcs.ANCHOR_INTERCEPT,
        "UNLISTED_DEFAULT": dwcs.UNLISTED_DEFAULT,
        "PROMO_TIERS": dwcs.PROMO_TIERS,
        "PROMO_ALIASES": dwcs.PROMO_ALIASES,
        "AGE_CORE_BONUS": dwcs.AGE_CORE_BONUS,
        "AGE_WINDOW_BONUS": dwcs.AGE_WINDOW_BONUS,
        "AGE_TAIL_PENALTY": dwcs.AGE_TAIL_PENALTY,
    }
    body = json.dumps({"ONE": one_tables, "DWCS": dwcs_tables}, separators=(",", ":"))
    return (
        "// GENERATED by scoring/export_tables.py from the Python formulas. Do not edit by hand.\n"
        "// ONE ASCENT and DWCS ASCENT are separate formulas with separate data. They are never combined.\n"
        "(function (root) {\n"
        f"  var T = {body};\n"
        "  if (typeof module !== 'undefined' && module.exports) module.exports = T;\n"
        "  else root.ASCENT_TABLES = T;\n"
        "})(this);\n"
    )


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(build())
    print("wrote", os.path.relpath(OUT))
