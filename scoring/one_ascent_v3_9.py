def promo_points(code: str) -> float:
    """Promotion points from the promotion's share of ONE signings."""
    if code in PROMO_OVERRIDES:
        return PROMO_OVERRIDES[code]
    return float(PROMO_TABLE[code][0]) if code in PROMO_TABLE else UNLISTED_PROMO


def hq_bonus(code: str) -> float:
    region = PROMO_TABLE[code][1] if code in PROMO_TABLE else "Unknown"
    return float(HQ_BONUS.get(region, 0))


def age_mod(age: Union[float, str, None]) -> float:
    if not isinstance(age, (int, float)) or isinstance(age, bool):   # blank or "N/A" = 0 points
        return 0.0
    for upper, mod in AGE_BANDS:
        if age <= upper:
            return mod
    return AGE_OLDER


def title_bonus(title_wins: Optional[int]) -> float:
    w = int(title_wins or 0)
    return 0.0 if w <= 0 else TITLE_BASE + TITLE_PER_WIN * w


def ascent_v39(*, wins: int, losses: int, draws: int, finish_rate_pct: float,
                weight_class: str, age, main_promotion: str,
                title_wins: int = 0, country: str = "",
                breakdown: bool = False) -> Union[float, Dict[str, Any]]:
    """ONE ASCENT v3.9. finish_rate_pct = finishes / wins x 100."""
    draws = draws or 0
    total = wins + losses + draws
    win_rate = round(100.0 * wins / total, 1) if total else 0.0   # workbook rounds to 1 dp

    wc_avg = WC_AVG.get(weight_class, GLOBAL_FR_AVG)
    fr_shrunk = (finish_rate_pct * wins + SHRINK_K * wc_avg) / (wins + SHRINK_K)
    fr_norm = min(FR_NORM_CEILING, max(0.0, fr_shrunk / wc_avg * GLOBAL_FR_AVG))
    base80 = fr_norm * FR_WEIGHT + win_rate * WR_WEIGHT

    p_pts = promo_points(main_promotion)
    hq = hq_bonus(main_promotion)
    region = COUNTRY_REGION.get(country, "Unknown")
    origin = ORIGIN_FIT.get(region, UNKNOWN_ORIGIN)
    a_mod = age_mod(age)
    t_bonus = title_bonus(title_wins)
    unbeaten = UNDEFEATED_BONUS if (losses == 0 and wins >= UNDEFEATED_MIN_WINS) else 0.0

    score = round(max(SCORE_FLOOR, base80 + p_pts + hq + origin + a_mod + t_bonus + unbeaten), 1)
    if not breakdown:
        return score
    return dict(score=score, win_rate=win_rate, wc_avg=wc_avg, fr_shrunk=round(fr_shrunk, 2),
                fr_norm=round(fr_norm, 2), base80=round(base80, 2), promo_pts=p_pts, hq_bonus=hq,
                origin_region=region, origin_fit=origin, age_mod=a_mod, title_bonus=t_bonus,
                undefeated_bonus=unbeaten)


